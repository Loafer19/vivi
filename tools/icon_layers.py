#!/usr/bin/env python3
"""Split two-tone icons into colour layers so Slint can tint each one from the theme.

For assets/icons/<p>.svg this writes assets/icons/layers/<p with / as _>-{b,a,d}.svg:
b = text-coloured parts, a = accent (#D37918), d = dim accent (#AB6314).
Parts of other layers get paint "none", so geometry and stacking order stay intact.

It also writes ui/core/duo.slint: the `Duo` lookup from an icon name to its layers, used by
TriIcon { name: "..." } and IconButton { duo: "..." }. A name resolves to the layers of
<name>-twotone.svg when it has both text-coloured and accent parts, else to the layers of
<name>.svg when it has accent parts, else to the plain <name>.svg (single-tone, no accent layers).
All-accent art (*-active, menu rows) is never picked for a plain name: it reads as "active".
`Duo.single(name)` is the plain <name>.svg of a two-tone name, for TriIcon `flat` (player bars set
to Single-tone).
Run after changing an icon:  python3 tools/icon_layers.py
"""
import re, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent / "assets/icons"
OUT = ROOT / "layers"
DUO = ROOT.parent.parent / "ui/core/duo.slint"
ACC, DIM = "#D37918", "#AB6314"
PAINT = re.compile(r'((?:fill|stroke)=")(#[0-9A-Fa-f]{3,8})(")')

def layer(svg, keep):
    def sub(m):
        c = m.group(2).upper()
        kind = "a" if c == ACC else "d" if c == DIM else "b"
        return m.group(0) if kind == keep else m.group(1) + "none" + m.group(3)
    return PAINT.sub(sub, svg)

def duo_slint(layered, plain, single):
    """layered: name -> layer stem; plain: name -> svg path relative to assets/icons;
    single: name -> its single-tone svg (for TriIcon `flat`)."""
    url = lambda p: f'@image-url("../../assets/icons/{p}")'
    def fn(fname, entries, fallback):
        lines = [f"    pure public function {fname}(name: string) -> image {{"]
        lines += [f'        if (name == "{n}") {{ return {url(p)}; }}' for n, p in entries]
        lines += [f"        {fallback}", "    }"]
        return lines
    names = sorted(layered)
    base = [(n, f"layers/{layered[n]}-b.svg") for n in names] + sorted(plain.items())
    out = ["// Generated by tools/icon_layers.py; do not edit by hand.",
           "// Icon name -> two-tone layers (base / accent / dim). Names without layers return the",
           "// plain icon as the base and no accent layers, so they draw single-tone.",
           "export global Duo {"]
    out += fn("base", base, '@image-url("")')
    out += fn("accent", [(n, f"layers/{layered[n]}-a.svg") for n in names], '@image-url("")')
    out += fn("dim", [(n, f"layers/{layered[n]}-d.svg") for n in names], '@image-url("")')
    # Single-tone art of a two-tone name (TriIcon `flat`, e.g. the player bars set to
    # Single-tone); names without one draw their layers in one colour.
    out += fn("single", [(n, single[n]) for n in names if n in single], '@image-url("")')
    out.append("}")
    return "\n".join(out) + "\n"

def main():
    OUT.mkdir(exist_ok=True)
    (OUT / "empty.svg").write_text('<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24"/>')
    stems, plain, mixed = set(), {}, set()
    for p in sorted(ROOT.rglob("*.svg")):
        if OUT in p.parents:
            continue
        name = str(p.relative_to(ROOT).with_suffix("")).replace("/", "_")
        svg = p.read_text()
        if ACC not in svg.upper() and DIM not in svg.upper():
            if p.parent == ROOT:
                plain[name] = p.name
            continue
        for k in "bad":
            (OUT / f"{name}-{k}.svg").write_text(layer(svg, k))
        stems.add(name)
        if any(m.group(2).upper() not in (ACC, DIM) for m in PAINT.finditer(svg)):
            mixed.add(name)
    layered = {}
    for s in sorted(stems):
        if s.startswith("menu_"):
            continue  # menu rows have their own lookup (Icons.menu)
        if s.endswith("-twotone"):
            if s in mixed:
                layered[s[: -len("-twotone")]] = s
        elif s + "-twotone" not in mixed:
            layered[s] = s
    single = {n: plain[n] for n in layered if n in plain}
    plain = {n: f for n, f in plain.items() if n not in layered and not n.endswith("-twotone")}
    DUO.write_text(duo_slint(layered, plain, single))

if __name__ == "__main__":
    main()
